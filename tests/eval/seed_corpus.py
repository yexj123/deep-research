"""Seed a dated corpus snapshot, so the O-16 staleness experiment is runnable later.

O-16 asks what a corpus costs once it stops refreshing. **The experiment needs time to pass,
not compute** -- it compares a review written from months-old papers against one written from
today's. That means the old corpus has to exist *before* the wait, which is what this builds.

    uv run python -m tests.eval.seed_corpus            # build it (arXiv only, no model, free)
    uv run python -m tests.eval.seed_corpus --rebuild  # recreate it from the manifest, no network

**Nothing here calls a model.** Seeding is `search_arxiv` plus `index_sources`, both already
tested, so the snapshot costs only wall-clock under arXiv's rate limit (D-064).

**Why a JSON manifest and not the .sqlite file.** `*.sqlite` is gitignored (D-010), so a
snapshot living only on disk is one machine wipe from gone -- and a corpus that cannot be
rebuilt is not evidence. The manifest holds every paper in full, so `--rebuild` reconstructs
the snapshot byte-for-byte relevant fields and with the **original** `indexed_at`.

**The one thing to be honest about:** `index_sources` stamps `indexed_at = now` and takes no
override (see its source), so `--rebuild` back-stamps the dates afterwards from the manifest.
The stamp is therefore *asserted by the manifest*, not observed by the database. That is fine
for this experiment -- the manifest is committed and dated in git, which is a stronger record
than a local file's mtime -- but a reader should know the difference.
"""

import argparse
import asyncio
import json
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

import httpx

from deep_research.agent.sources.arxiv import build_search_query, search_arxiv
from deep_research.agent.sources.models import Source
from deep_research.persistence.corpus import connect, index_sources, stats

QUESTIONS_FILE = Path(__file__).parent / "questions-staleness.json"
MANIFEST_FILE = Path(__file__).parent / "snapshots" / "corpus-seed.json"
# Its own database, never the live one: seeding into `deep_research.sqlite` would mix the
# snapshot into whatever the app has already indexed, and the "stale" arm would silently
# contain papers found last week.
SNAPSHOT_DB = Path(__file__).parent / "snapshots" / "corpus-seed.sqlite"

# Per seed query. Larger than ARXIV_MAX_RESULTS on purpose: the agent searches per *subtopic*
# and needs only enough to answer one, while this needs enough breadth that a subtopic nobody
# has written yet still finds MIN_LOCAL_PAPERS matches months from now.
SEED_MAX_RESULTS = 60
RATE_LIMIT_SECONDS = 3


def load_questions() -> list[dict]:
    return json.loads(QUESTIONS_FILE.read_text(encoding="utf-8"))["questions"]


def seed_queries(entry: dict) -> list[str]:
    """The question itself plus its committed facets.

    Facets are in the question file rather than generated by a planner: a model-written
    subtopic list would be non-reproducible and would quietly change what the snapshot
    contains between runs, which is the one thing a frozen artifact must not do (D-088).
    """
    return [entry["question"], *entry.get("facets", [])]


async def fetch(entry: dict) -> tuple[list[Source], list[str]]:
    """Every paper arXiv returns for this question's seed queries, deduplicated."""
    found: dict[str, Source] = {}
    errors: list[str] = []
    async with httpx.AsyncClient(timeout=30) as client:
        for query_text in seed_queries(entry):
            try:
                result = await search_arxiv(
                    client, build_search_query(query_text), SEED_MAX_RESULTS
                )
            except Exception as exc:  # noqa: BLE001 - reported per query, never fatal
                errors.append(f"{query_text!r}: {type(exc).__name__}: {exc}")
                continue
            for source in result.sources:
                found.setdefault(source.arxiv_id, source)
            await asyncio.sleep(RATE_LIMIT_SECONDS)
    return list(found.values()), errors


def to_record(source: Source) -> dict:
    """A Source as JSON. `published` is a datetime, which json cannot take directly."""
    record = asdict(source)
    record["published"] = source.published.isoformat()
    record["authors"] = list(source.authors)
    return record


def from_record(record: dict) -> Source:
    return Source(
        arxiv_id=record["arxiv_id"],
        version=record["version"],
        title=record["title"],
        authors=tuple(record["authors"]),
        summary=record["summary"],
        published=datetime.fromisoformat(record["published"]),
        url=record["url"],
        excerpt=record.get("excerpt", ""),
    )


def write_snapshot(manifest: dict) -> None:
    """Build the snapshot database from a manifest, stamping the manifest's own seed date."""
    SNAPSHOT_DB.parent.mkdir(parents=True, exist_ok=True)
    if SNAPSHOT_DB.exists():
        SNAPSHOT_DB.unlink()
    db = connect(str(SNAPSHOT_DB))
    try:
        sources = [from_record(r) for entry in manifest["questions"] for r in entry["papers"]]
        index_sources(db, sources)
        # Back-stamp: see the module docstring. Without this a rebuild in 2027 would produce a
        # corpus dated 2027, and the whole point is a corpus dated when it was seeded.
        with db:
            db.execute("UPDATE papers SET indexed_at = ?", (manifest["seeded_at"],))
        summary = stats(db)
        print(
            f"snapshot: {summary['papers']} papers, {summary['chunks']} chunks, "
            f"indexed_at {summary['indexed_from']}"
        )
        print(f"          {SNAPSHOT_DB}")
    finally:
        db.close()


async def build() -> None:
    seeded_at = datetime.now(UTC).isoformat()
    entries = load_questions()
    manifest: dict = {
        "version": 1,
        "seeded_at": seeded_at,
        "question_set": "staleness",
        "seed_max_results": SEED_MAX_RESULTS,
        "purpose": "O-16: the stale arm of the staleness experiment. See docs/staleness-experiment.md.",
        "questions": [],
    }

    for entry in entries:
        sources, errors = await fetch(entry)
        newest = max((s.published for s in sources), default=None)
        manifest["questions"].append(
            {
                "id": entry["id"],
                "arm": entry["arm"],
                "question": entry["question"],
                "queries": seed_queries(entry),
                "paper_count": len(sources),
                # The newest paper in the snapshot. In a later run, any retrieved paper
                # published after this could not possibly have been in the corpus -- which is
                # what makes "the stale arm missed it" a fact rather than an inference.
                "newest_published": newest.isoformat() if newest else None,
                "errors": errors,
                "papers": [to_record(s) for s in sorted(sources, key=lambda s: s.arxiv_id)],
            }
        )
        flag = f"  ({len(errors)} query error(s))" if errors else ""
        print(f"  {entry['id']:<14} {entry['arm']:<5} {len(sources):>4} papers{flag}")

    MANIFEST_FILE.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_FILE.write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    total = sum(q["paper_count"] for q in manifest["questions"])
    print(f"\nmanifest: {total} papers across {len(entries)} questions -> {MANIFEST_FILE}")
    write_snapshot(manifest)


def rebuild() -> None:
    if not MANIFEST_FILE.exists():
        raise SystemExit(f"no manifest at {MANIFEST_FILE}; run without --rebuild first")
    write_snapshot(json.loads(MANIFEST_FILE.read_text(encoding="utf-8")))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rebuild",
        action="store_true",
        help="recreate the snapshot database from the committed manifest, with no network",
    )
    if parser.parse_args().rebuild:
        rebuild()
    else:
        asyncio.run(build())


if __name__ == "__main__":
    main()
